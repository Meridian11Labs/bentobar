"""Writes the Sunset item's table of places: each time zone's main city and where it is.

Reads tzdata's zone.tab (public domain: one row per zone and country, with the coordinates of the
city the zone is named after) and writes app/src/main/java/com/meridian11/books/bentobar/items/SunZones.kt,
with the city as the zone id's last part (spaces for underscores) and the coordinates to 0.1 degree.
Nothing is downloaded: give it the zone.tab of a tzdata release, which most systems carry.

    python3 tools/zones.py PATH/TO/zone.tab [TZDATA_VERSION]

The version goes into the file's header. Without one it is read from a `+VERSION` or `version` file beside
zone.tab (macOS keeps the first, a tzdata release the second). Plain python3, no packages.
"""
from __future__ import annotations

import pathlib
import sys
from fractions import Fraction

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "app/src/main/java/com/meridian11/books/bentobar/items/SunZones.kt"


def angle(text: str) -> Fraction:
    """ISO 6709 as zone.tab writes it: a sign, degrees (two figures for latitude, three for longitude), minutes, maybe seconds."""
    sign = -1 if text[0] == "-" else 1
    digits = text[1:]
    deg_len = 2 if len(digits) in (4, 6) else 3
    deg, rest = digits[:deg_len], digits[deg_len:]
    minutes, seconds = rest[:2], rest[2:] or "0"
    return sign * (Fraction(int(deg)) + Fraction(int(minutes), 60) + Fraction(int(seconds), 3600))


def tenth(value: Fraction) -> str:
    """To 0.1, a half away from zero, never "-0.0"."""
    sign = -1 if value < 0 else 1
    tenths = int(abs(value) * 10 + Fraction(1, 2))
    if tenths == 0:
        return "0.0"
    return f"{'-' if sign < 0 else ''}{tenths // 10}.{tenths % 10}"


def coordinates(field: str) -> tuple[Fraction, Fraction]:
    split = next(i for i in range(1, len(field)) if field[i] in "+-")
    return angle(field[:split]), angle(field[split:])


def version_beside(tab: pathlib.Path) -> str | None:
    for name in ("+VERSION", "version"):
        f = tab.parent / name
        if f.is_file():
            return f.read_text().strip()
    return None


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    tab = pathlib.Path(sys.argv[1])
    version = sys.argv[2] if len(sys.argv) == 3 else version_beside(tab)
    if not version:
        sys.exit("No tzdata version beside zone.tab: give it as the second argument.")
    rows = {}
    for line in tab.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        zone = fields[2]
        lat, lon = coordinates(fields[1])
        rows[zone] = (zone.rsplit("/", 1)[-1].replace("_", " "), tenth(lat), tenth(lon))
    lines = [
        "package com.meridian11.books.bentobar.items",
        "",
        f"// Generated by tools/zones.py from tzdata {version}'s zone.tab (public domain).",
        "// Do not edit: run it again with a newer zone.tab.",
        "",
        "/**",
        " * Each time zone's main city and where it is, to 0.1°: the place the Sunset item works out the sun's times for, with",
        " * no location asked of anyone ([SunRules.place]). The city is the zone's own name, the last part of its id.",
        " */",
        "object SunZones {",
        "    data class Place(val city: String, val lat: Double, val lon: Double)",
        "",
        "    val TABLE: Map<String, Place> = mapOf(",
    ]
    for zone in sorted(rows):
        city, lat, lon = rows[zone]
        lines.append(f'        "{zone}" to Place("{city}", {lat}, {lon}),')
    lines += ["    )", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(rows)} zones from tzdata {version} -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
